#!/usr/bin/env python3
"""Studio Job 12 (exploratory): Lean certificates for the 66666 2-ball verdicts.
For each selected pattern, emit `theorem tb_<pattern> : run cfg = { classes, ext, reached, depth } := by native_decide`
with the numbers dfast.cpp reported.  The theorem pins the whole closure result, so it certifies the D-reducible
verdict (reached = classes) or the non-D-reducible verdict (reached < classes), and any Lean-vs-dfast difference makes
that one theorem fail.  Files: ../../dcheck/TB_<set>_<k>.lean (one lean_lib each), a list for the build script.
Sets:
  dred    every D-reducible pattern with ring 8..13 (all), chunked by cost
  t14/t15 a fixed sample of 20 D-reducible patterns at ring 14 / 15, one theorem per file (timing)
  nd<r>   a fixed sample of up to 50 non-D-reducible patterns per ring 10..15
usage: gen_lean_2ball.py   (run in wheels/studio; reads configs_2ball.txt.gz, run9_results.txt.gz)"""
import gzip, os, random, collections
HERE = os.path.dirname(os.path.abspath(__file__)); DC = os.path.join(HERE, '../../dcheck')
conf = {}
for l in gzip.open(os.path.join(HERE, 'configs_2ball.txt.gz'), 'rt'):
    p = l.split(); conf[p[0]] = p
res = {}
for l in gzip.open(os.path.join(HERE, 'run9_results.txt.gz'), 'rt'):
    p = l.split()
    if 'D=' not in l: continue
    g = lambda k: int(next(x for x in p if x.startswith(k + '=')).split('=')[1])
    res[p[0]] = dict(r=g('r'), classes=g('classes'), ext=g('ext'), reached=g('reached'), depth=g('depth'), D=('D=true' in p))
rng = random.Random(12)
def arr(s): return '#[' + ', '.join('#[]' if t == '-' else '#[' + t.replace(',', ', ') + ']' for t in s.split(';')) + ']'
def thm(name):
    _, r, m, ra, ia = conf[name]; x = res[name]; pat = name[1:]
    return ('/-- 66666 2-ball, second ring %s (ring %s): dfast says %s. -/\n'
            'def cfg_%s : Conf := { name := "%s", r := %s, m := %s, ringAdj := %s, intAdj := %s }\n'
            'theorem tb_%s : run cfg_%s = { classes := %d, ext := %d, reached := %d, depth := %d } := by\n  native_decide\n'
            % (pat, r, 'D-reducible' if x['D'] else 'not D-reducible', pat, pat, r, m, arr(ra), arr(ia), pat, pat, x['classes'], x['ext'], x['reached'], x['depth']))
def write(fname, names, note):
    with open(os.path.join(DC, fname + '.lean'), 'w') as f:
        f.write('import DCheck\n/-! Studio Job 12 (exploratory): %s. Generated by wheels/studio/gen_lean_2ball.py.\n'
                'Each theorem pins `run` on one 66666 2-ball to the values dfast.cpp reported. -/\nnamespace DCheck\n\n' % note)
        for nm in names: f.write(thm(nm) + '\n')
        f.write('end DCheck\n\n' + ''.join('#print axioms DCheck.tb_%s\n' % nm[1:] for nm in names))
libs = []
byr = collections.defaultdict(list)
for nm, x in res.items(): byr[(x['r'], x['D'])].append(nm)
for k in byr: byr[k].sort()
# dred: rings 8..13, chunk by estimated cost (3.2^r), ~14 chunks
dred = [nm for r in range(8, 14) for nm in byr[(r, True)]]
cost = lambda nm: 3.2 ** res[nm]['r']
chunks = [[] for _ in range(14)]; load = [0] * 14
for nm in sorted(dred, key=cost, reverse=True):
    i = load.index(min(load)); chunks[i].append(nm); load[i] += cost(nm)
for i, ch in enumerate(chunks):
    ch.sort(key=lambda nm: (res[nm]['r'], nm)); f = 'TB_dred_%02d' % i; write(f, ch, 'D-reducible 66666 2-balls, rings 8-13, part %d of 14' % i); libs.append((f, len(ch)))
for r in (14, 15):
    for nm in rng.sample(byr[(r, True)], 20):
        f = 'TB_t%d_%s' % (r, nm[1:]); write(f, [nm], 'timing sample, ring %d, D-reducible' % r); libs.append((f, 1))
for r in range(10, 16):
    s = byr[(r, False)]; s = rng.sample(s, min(50, len(s)))
    if r <= 13:
        f = 'TB_nd%d' % r; write(f, sorted(s), 'non-D-reducible sample, ring %d' % r); libs.append((f, len(s)))
    else:
        for i in range(0, len(s), 5):
            f = 'TB_nd%d_%d' % (r, i // 5); write(f, sorted(s[i:i + 5]), 'non-D-reducible sample, ring %d, part %d' % (r, i // 5)); libs.append((f, len(s[i:i + 5])))
with open(os.path.join(HERE, 'lean12_libs.txt'), 'w') as f:
    for l, n in libs: f.write('%s %d\n' % (l, n))
print('dred', len(dred), 'files', len(libs), 'theorems', sum(n for l, n in libs))
