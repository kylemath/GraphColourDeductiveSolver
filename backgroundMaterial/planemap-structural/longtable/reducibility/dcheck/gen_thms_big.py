#!/usr/bin/env python3
"""Studio, 13 Oct 2026 (exploratory). Emit DCheckR12a..DCheckR14j.lean: the RSST agreement statement
for every configuration with ring 12-14, split into 16 files (ring 12: 2, ring 13: 4, ring 14: 10) so they
build in parallel. Each file proves `(#[cfg_i, ...]).all agreesRSST = true` by native_decide.
Also prints the lakefile stanzas.  Usage: gen_thms_big.py  (run in dcheck/)"""
import re
rings = {}
for m in re.finditer(r'def cfg_(\d+) : Conf := \{ name := "([^"]+)", r := (\d+)', open("DCheckData.lean").read()):
    rings.setdefault(int(m.group(3)), []).append(int(m.group(1)))
split = {12: 2, 13: 4, 14: 10}
libs = []
for r, k in split.items():
    ids = rings[r]
    for q in range(k):
        part = ids[q::k]  # interleave so file costs are balanced
        nm = "DCheckR%d%s" % (r, "abcdefghij"[q])
        libs.append(nm)
        thm = "rsst_r%d%s_agree" % (r, "abcdefghij"[q])
        # one theorem per chunk of <= 14 configurations: a single 49-88 element array literal hit the default
        # maxHeartbeats in isDefEq (ring 12/13, first attempt); 14 is the size that built at ring 14
        chunks = [part[i:i + 14] for i in range(0, len(part), 14)]
        thms = [thm if len(chunks) == 1 else "%s_%d" % (thm, c) for c in range(len(chunks))]
        with open(nm + ".lean", "w") as f:
            f.write("import DCheckThms\n/-! Ring %d, part %s of %d (%d configurations; generated by gen_thms_big.py).\n"
                    "Exploratory: says what the checker computes, agreeing with RSST's data. -/\nnamespace DCheck\n"
                    % (r, "abcdefghij"[q], k, len(part)))
            for t, ch in zip(thms, chunks):
                f.write("theorem %s : (#[%s] : Array Conf).all agreesRSST = true := by\n  native_decide\n"
                        % (t, ", ".join("cfg_%d" % i for i in ch)))
            f.write("end DCheck\n" + "".join("#print axioms DCheck.%s\n" % t for t in thms))
print("\n".join("\nlean_lib %s" % l for l in libs))
print(sum(len(rings[r]) for r in split), "configurations")
