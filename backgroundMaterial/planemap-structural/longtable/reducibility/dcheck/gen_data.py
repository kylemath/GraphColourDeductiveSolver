#!/usr/bin/env python3
"""Emit DCheckData.lean: all RSST configurations from unavoidable.conf as Lean data
(name, ring size r, interior size m, ring neighbours / interior neighbours of each interior vertex,
RSST's extendable-class count and contract size).  Usage: gen_data.py CONF OUT.lean"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.argv, args = sys.argv[:1] + [sys.argv[1], "0"], sys.argv[1:]
import io, contextlib
with contextlib.redirect_stdout(io.StringIO()):
    import rsst_scan  # parses at import (prints histogram); we only use parse
cf = rsst_scan.parse(args[0])
L = ["import DCheck", "/-! Generated by gen_data.py from RSST unavoidable.conf (633 configurations).",
     "`cfg_i` is the i-th configuration (0-based, file order); `rsst` is the array of all. -/",
     "namespace DCheck", ""]
for i, c in enumerate(cf):
    r, n = c["r"], c["n"]; m = n - r
    ra = [[t - 1 for t in c["adj"][r + 1 + a] if t <= r] for a in range(m)]
    ia = [[t - r - 1 for t in c["adj"][r + 1 + a] if t > r] for a in range(m)]
    L.append('/-- RSST %s -/\ndef cfg_%d : Conf := { name := "%s", r := %d, m := %d, ringAdj := #[%s], intAdj := #[%s], rsstExt := %d, rsstContract := %d }'
             % (c["name"], i, c["name"], r, m, ", ".join("#[%s]" % ", ".join(map(str, x)) for x in ra),
                ", ".join("#[%s]" % ", ".join(map(str, x)) for x in ia), c["next"], c["contr"]))
chunks = [list(range(j, min(j + 40, len(cf)))) for j in range(0, len(cf), 40)]
for q, ch in enumerate(chunks):
    L.append("def rsstChunk%d : Array Conf := #[%s]" % (q, ", ".join("cfg_%d" % i for i in ch)))
L.append("def rsst : Array Conf := " + " ++ ".join("rsstChunk%d" % q for q in range(len(chunks))))
L += ["", "end DCheck", ""]
open(args[1], "w").write("\n".join(L))
print(len(cf), "configurations written")
