#!/usr/bin/env python3
"""Studio Job 21 (exploratory): Lean certificates for the C-candidate wheels of Job 17 (the Job 16 recipe).
For each C-candidate wheel other than 66666 (Job 16), pick a working X (from census17_full.txt.gz) whose contracted
components each contain at most ONE ring vertex (then G/X has no loop for any G in which the wheel appears: a loop
needs an edge between two identified vertices, and interior neighbourhoods are fully given by the configuration);
re-check no-loop inside the configuration; and emit, in ../../dcheck/CWheels.lean:
  run cfg = {classes, ext, reached, depth}           (pins the D-closure, from cfast's numbers)
  every ring colouring that extends after contracting X is in runGood's good set   (the computational half)
Wheels whose every working X has a component with >= 2 ring vertices are listed as NOT certified (an outside chord
between those ring vertices could make a loop in G/X).  Writes cwheels21.json (wheel, X, components, status)."""
import gzip, re, json, os, collections
HERE = os.path.dirname(os.path.abspath(__file__)); DC = os.path.join(HERE, '../../dcheck')
conf = {l.split()[0]: l.split() for l in open(os.path.join(HERE, 'wheels17.txt'))}
cur = None; Xs = collections.defaultdict(list); nums = {}
for l in gzip.open(os.path.join(HERE, 'census17_full.txt.gz'), 'rt'):
    if re.match(r'^c[56]_', l):
        cur = l.split()[0]
        g = lambda k: int(re.search(k + r'=(\d+)', l).group(1))
        nums[cur] = (g('classes'), g('ext'), g('reached'), g('depth'))
    elif 'C-REDUCIBLE with' in l:
        Xs[cur].append(l.split('X={')[1].split('}')[0].split(','))
def parse(s): return [[int(x) for x in t.split(',')] if t != '-' else [] for t in s.split(';')]
def comps(X, r):
    par = {}
    def f(v):
        par.setdefault(v, v)
        while par[v] != v: par[v] = par[par[v]]; v = par[v]
        return v
    for e in X:
        a, b = e.split('-'); par[f(a)] = f(b)
    C = collections.defaultdict(set)
    for v in list(par): C[f(v)].add(v)
    return [sorted(c) for c in C.values()]
def noloop(X, name):
    _, r, m, ra, ia = conf[name]; r = int(r); ra, ia = parse(ra), parse(ia)
    E = set()
    for a in range(len(ra)):
        for t in ra[a]: E.add(tuple(sorted(('R%d' % t, 'I%d' % a))))
        for b in ia[a]: E.add(tuple(sorted(('I%d' % a, 'I%d' % b))))
    for t in range(r): E.add(tuple(sorted(('R%d' % t, 'R%d' % ((t + 1) % r)))))
    Xset = {tuple(sorted(e.split('-'))) for e in X}
    for c in comps(X, r):
        cs = set(c)
        for e in E:
            if e not in Xset and e[0] in cs and e[1] in cs: return False
    return True
out = []; lean = ['import C66666', '/-! Studio Job 21 (exploratory): Lean certificates for the C-candidate wheels of Job 17 (recipe of Job 16, C66666.lean).',
                  'For each wheel: `run` pinned to cfast''s numbers, and every ring colouring that extends after contracting X is in the',
                  'good set of `runGood` (the verbatim copy of `run`).  Generated by discharge/studio17/gen_lean21.py. -/', 'namespace DCheck', '']
thms = []
def arr(s): return '#[' + ', '.join('#[]' if t == '-' else '#[' + t.replace(',', ', ') + ']' for t in s.split(';')) + ']'
for w in sorted(Xs):
    if w == 'c5_66666': continue
    good = [X for X in Xs[w] if all(sum(v.startswith('R') for v in c) <= 1 for c in comps(X, 0)) and noloop(X, w)]
    rec = dict(wheel=w, ring=int(conf[w][1]), workingX_listed=len(Xs[w]))
    if not good:
        rec.update(status='NOT certified (every listed working X has a component with >= 2 ring vertices)', X=Xs[w][0], components=comps(Xs[w][0], 0))
        out.append(rec); continue
    X = min(good, key=len); rec.update(status='Lean', X=X, components=comps(X, 0))
    out.append(rec)
    nm = w.replace('c5_', 'w5_').replace('c6_', 'w6_'); _, r, m, ra, ia = conf[w]
    eqR = [(int(b[1:]), int(a[1:])) if a.startswith('I') else (int(a[1:]), int(b[1:])) for a, b in (e.split('-') for e in X) if 'R' in a + b]
    eqI = [(int(a[1:]), int(b[1:])) for a, b in (e.split('-') for e in X) if 'R' not in a + b]
    c, e_, rc, d = nums[w]
    lean += ['/-- %s, X = {%s} -/' % (w, ','.join(X)),
             'def cfg_%s : Conf := { name := "%s", r := %s, m := %s, ringAdj := %s, intAdj := %s }' % (nm, w, r, m, arr(ra), arr(ia)),
             'theorem %s_run : run cfg_%s = { classes := %d, ext := %d, reached := %d, depth := %d } := by native_decide' % (nm, nm, c, e_, rc, d),
             'theorem %s_extX_reached :' % nm,
             '    (let p := runGood cfg_%s; (List.range p.1.size).all fun i =>' % nm,
             '      !(extCAux cfg_%s %s %s p.1[i]! cfg_%s.m #[]) || p.2[i]!) = true := by native_decide' % (nm, str(eqR).replace('(', '(').replace(' ', ''), str(eqI).replace(' ', ''), nm), '']
    thms += ['%s_run' % nm, '%s_extX_reached' % nm]
lean += ['end DCheck', ''] + ['#print axioms DCheck.%s' % t for t in thms]
open(os.path.join(DC, 'CWheels.lean'), 'w').write('\n'.join(lean) + '\n')
json.dump(out, open(os.path.join(HERE, 'cwheels21.json'), 'w'), indent=1)
for o in out: print(o['wheel'], o['ring'], o['status'], ','.join(o['X']), o['components'])
