#!/usr/bin/env python3
"""ST-120 B2 follow-up: generate RSSTRulesN2.lean, the N2 parts of RSSTFP_SPEC_v2.md (md5 122da06a) §16.2.

§16.2 row N2: hub 7, spokes [hats] at positions 0..6 = `=6 =5[=5] g2 =6 =6[=5] g5 =5`, target = position 2 (g2),
amount 1, exact letters (9 = 9+), (g2, g5) in {(9,7), (9,8), (9,9), (8,8)}.  §16.1: hat = the apex before the spoke
(across the edge to the previous spoke) = spec §3 hat; mirror = pubrules mirror, added unless contained in the part.
Each (g2, g5) is written as a Gonthier-style part string and run through gen_rules.parse_part / mirror / psub, the
same §3.1-3.2 code path as the 71 parts.  usage: python3 -I gen_rules_n2.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_rules as G  # noqa: E402

OUT = os.path.join(HERE, 'RSSTRulesN2.lean')
PAIRS = [(9, 7), (9, 8), (9, 9), (8, 8)]

def n2_parts():
    out = []
    for g2, g5 in PAIRS:
        body = ' $ 6 $[5] 5 $ %d $ 6 $[5] 6 $ %d $ 5 $' % (g2, g5)   # Part $ =6 $ [=5] =5 $ g2 $ =6 $ [=5] =6 $ g5 $ =5 $
        p = G.parse_part(body)
        base = 'N2_%d%d' % (g2, g5)
        out.append((base, base, False, p))
        mp = G.mirror(p)
        if not G.psub(mp, p):
            out.append((base + 'm', base, True, mp))
    return out

HEADER = '''import RSSTView

/-
  GENERATED by gen_rules_n2.py; do not edit by hand.
  Source: RSSTFP_SPEC_v2.md (md5 122da06a, commit f52992e45) §16.2 row N2, conventions §16.1.
-/

/-!
# ST-120 B2 follow-up: the 8 N2 parts and the 79-part list

N2 (§16.2): hub 7, `=6 =5[=5] g2 =6 =6[=5] g5 =5`, target position 2 (g2), amount 1, exact letters (9 = 9+),
(g2, g5) ∈ {(9,7), (9,8), (9,9), (8,8)}; each with its mirror (none is mirror-contained), 8 unit parts.
Tags `N2_<g2><g5>` and `N2_<g2><g5>m`.
-/

namespace SimpleGraph.SphericalMap.RSSTSeed

/-- The 8 N2 parts (RSSTFP_SPEC_v2 §16.2). -/
def rsstPartsN2 : List Part := [
'''

FOOTER = '''
]

/-- The 71 RSST parts followed by the 8 N2 parts. -/
def rsstParts79 : List Part := rsstParts ++ rsstPartsN2

theorem rsstPartsN2_length : rsstPartsN2.length = 8 := by decide

theorem rsstParts79_length : rsstParts79.length = 79 := by decide

/-- By hub letter: 6 / 14 / 48 / 11 (the 8 N2 parts are 7-hubs). -/
theorem rsstParts79_count_by_hub :
    (rsstParts79.filter (·.hub == 5)).length = 6 ∧ (rsstParts79.filter (·.hub == 6)).length = 14 ∧
    (rsstParts79.filter (·.hub == 7)).length = 48 ∧ (rsstParts79.filter (·.hub == 8)).length = 11 := by decide

theorem rsstParts79_wellShaped : rsstParts79.all Part.wellShaped = true := by decide

theorem rsstParts79_local : rsstParts79.all Part.isLocal = true := by decide

end SimpleGraph.SphericalMap.RSSTSeed
'''

def main():
    parts = n2_parts()
    assert len(parts) == 8, len(parts)
    lines = []
    for t, base, mir, p in parts:
        lines.append('  { tag := "%s", base := "%s", isMirror := %s, hub := %d, target := 2, amount := 1,\n    subs := [%s] }'
                     % (t, base, 'true' if mir else 'false', len(p), ',\n             '.join(G.lsub(s) for s in p)))
    txt = HEADER + ',\n'.join(lines) + FOOTER
    open(OUT, 'w').write(txt)
    for t, _, _, p in parts:
        print(t, '  '.join('%s[%s]' % (G.lr(s[0]), G.lr(s[1])) for s in p))
    print('wrote %s (%d lines)' % (OUT, txt.count('\n')))

if __name__ == '__main__':
    main()
