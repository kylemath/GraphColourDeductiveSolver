#!/usr/bin/env python3
"""ST-120 B5: a kill list as Lean data (RSSTKillSet<NAME>.lean): the selection export_cert.kill_sel(MODEL) of the 633,
in rsst.txt order, as `def k<NAME> : List Conf` (filter of RSSTConfs.k633 by a generated mask).
usage: python3 -I gen_killset.py NAME MODEL      e.g. gen_killset.py 583 583"""
import os, sys
H = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, H)
import export_cert as E
name, model = sys.argv[1], sys.argv[2]
sel = set(E.kill_sel(model))
mask = ['true' if i in sel else 'false' for i in range(633)]
L = ['/- GENERATED by py/gen_killset.py %s %s; do not edit by hand. %d configurations. -/' % (name, model, len(sel)),
     'import RSSTConfs', '', 'namespace SimpleGraph.SphericalMap.RSSTSeed', '',
     'def k%sMask : List Bool := [%s]' % (name, ', '.join(mask)), '',
     '/-- Kill list `%s` (%d configurations, rsst.txt order). -/' % (model, len(sel)),
     'def k%s : List Conf := (k633.zip k%sMask).filterMap fun (K, b) => if b then some K else none' % (name, name), '',
     'theorem k%s_sub : ∀ K ∈ k%s, K ∈ k633 := by' % (name, name),
     '  intro K hK',
     '  obtain ⟨⟨K\', b⟩, hm, he⟩ := List.mem_filterMap.1 hK',
     '  by_cases hb : b = true',
     '  · simp [hb] at he; subst he; exact (List.of_mem_zip hm).1',
     '  · simp [hb] at he', '',
     'end SimpleGraph.SphericalMap.RSSTSeed']
open(os.path.join(H, '..', 'RSSTKillSet%s.lean' % name), 'w').write('\n'.join(L) + '\n')
print('k%s: %d configurations' % (name, len(sel)))
