#!/usr/bin/env python3
"""ST-120 B5 rot: K's interior rotations for a kc kill list, as Lean data (RSSTKillRot<NAME>.lean), aligned with
RSSTKill<NAME>.lean. Each interior vertex: its cyclic neighbour list, interior neighbour j as j, ring neighbour as 1000,
all oriented coherently (py/rotcheck.krot). Cross-check: for the rsst configurations, the cyclic order equals
unavoidable.conf's adjacency order (rcore.parse_conf) up to one global reflection per configuration.
usage: python3 -I gen_krot.py KCFILE NAME"""
import os, sys, hashlib
H = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, H)
import rotcheck as RC
R = RC.R
fn, name = sys.argv[1], sys.argv[2]
raw = open(fn, 'rb').read(); ls = [l for l in raw.decode().split('\n') if l.strip()]
conf = {c['name']: c for c in R.parse_conf()}
rows = []; chk = {'rsst_checked': 0, 'rsst_agree': 0, 'rsst_mirror': 0, 'rsst_DIFF': 0}
for l in ls:
    nm, r, m, cyc = RC.krot(l)
    rows.append([[1000 if y[0] == 'R' else y[1] for y in cyc[j]] for j in range(m)])
    if nm.startswith('rsst'):
        c = conf[nm.split('_', 1)[1].replace('o', '.')]; chk['rsst_checked'] += 1
        # conf vertex ids: ring 1..r, interior r+1..n -> ours: ring ('R', v-1), interior ('I', v-r-1)
        mp = lambda v: ('R', v - 1) if v <= r else ('I', v - r - 1)
        def same(a, b):
            if len(a) != len(b): return False
            return any(all(a[(o + k) % len(a)] == b[k] for k in range(len(b))) for o in range(len(a)))
        s1 = all(same([mp(v) for v in c['adj'][r + 1 + j]], cyc[j]) for j in range(m))
        s2 = all(same([mp(v) for v in reversed(c['adj'][r + 1 + j])], cyc[j]) for j in range(m))
        chk['rsst_agree' if s1 else 'rsst_mirror' if s2 else 'rsst_DIFF'] += 1
print(chk)
L = ['/-', '  GENERATED by py/gen_krot.py from %s (md5 %s); do not edit by hand.' % (os.path.relpath(fn, os.path.join(H, '..')), hashlib.md5(raw).hexdigest()[:8]),
     '  Interior rotations (coherently oriented link cycles; interior neighbour j, ring 1000), aligned with k%s.' % name,
     '  rsst entries vs unavoidable.conf adjacency order: %s' % chk, '-/',
     'import RSSTKill%s' % name, 'import RSSTKillRotCore', '', 'namespace SimpleGraph.SphericalMap.RSSTSeed', '',
     '/-- One string per configuration: vertices separated by `;`, neighbours by `,`. -/',
     'def k%sRotS : List String := [' % name,
     ',\n'.join('  "%s"' % ';'.join(','.join(map(str, x)) for x in row) for row in rows), ']', '',
     'def parseRot (s : String) : List (List Nat) := (s.splitOn ";").map fun v => (v.splitOn ",").map String.toNat!', '',
     'def k%sRot : List (List (List Nat)) := k%sRotS.map parseRot' % (name, name), '',
     '/-- K%s with rotations. -/' % name, 'def k%sR : List ConfR := k%s.zip k%sRot' % (name, name, name), '',
     'end SimpleGraph.SphericalMap.RSSTSeed']
open(os.path.join(H, '..', 'RSSTKillRot%s.lean' % name), 'w').write('\n'.join(L) + '\n')
