#!/usr/bin/env python3
"""ST-127: a kill list as Lean data from kc lines (rsst.txt format), in file order.
usage: python3 -I gen_killkc.py KCFILE NAME   -> RSSTKill<NAME>.lean with `def k<NAME> : List Conf`"""
import os, sys, hashlib
H = os.path.dirname(os.path.abspath(__file__))
fn, name = sys.argv[1], sys.argv[2]
raw = open(fn, 'rb').read(); ls = [l for l in raw.decode().split('\n') if l.strip()]
ents = []
for l in ls:
    f = l.split(); m = int(f[2])
    rl = [[] if x == '-' else x.split(',') for x in f[3].split(';')]
    il = [[] if x == '-' else [int(y) for y in x.split(',')] for x in f[4].split(';')]
    assert len(rl) == m == len(il)
    for j in range(m):
        for k in il[j]: assert j in il[k], (f[0], j, k)
    deg = [len(rl[j]) + len(il[j]) for j in range(m)]
    ents.append('  ⟨"%s", [%s], [%s]⟩' % (f[0], ','.join(map(str, deg)), ','.join('[%s]' % ','.join(map(str, sorted(x))) for x in il)))
L = ['/-', '  GENERATED by py/gen_killkc.py from %s (md5 %s); do not edit by hand.' % (os.path.relpath(fn, os.path.join(H, '..')), hashlib.md5(raw).hexdigest()[:8]),
     '  %d configurations: interior degrees and interior adjacency (0-based), in file order.' % len(ents), '-/',
     'import RSSTKill', '', 'namespace SimpleGraph.SphericalMap.RSSTSeed', '',
     'def k%s : List Conf := [' % name, ',\n'.join(ents), ']', '',
     'set_option maxRecDepth 40000 in', 'theorem k%s_length : k%s.length = %d := by rfl' % (name, name, len(ents)), '',
     'end SimpleGraph.SphericalMap.RSSTSeed']
open(os.path.join(H, '..', 'RSSTKill%s.lean' % name), 'w').write('\n'.join(L) + '\n')
print(name, len(ents))
