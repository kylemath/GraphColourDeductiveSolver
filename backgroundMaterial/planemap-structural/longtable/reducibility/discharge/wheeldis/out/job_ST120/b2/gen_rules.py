def main():
    md5, names, parts = load()
    byn = collections.Counter(len(p) for _, _, _, p in parts)
    assert len(parts) == 71, len(parts)
    assert [byn[k] for k in (5, 6, 7, 8)] == [6, 14, 40, 11], byn
    nomir = [t for t, _, _, p in parts if not t.endswith('m') and (t + 'm') not in {x[0] for x in parts}]
    # no part has m(p) strictly inside p (spec §3.2)
    for t, _, mir, p in parts:
        if not mir:
            mp = mirror(p)
            assert not (psub(mp, p) and mp != p), t
    lines = []
    for t, base, mir, p in parts:
        lines.append('  { tag := "%s", base := "%s", isMirror := %s, hub := %d, target := 2, amount := 1,\n    subs := [%s] }'
                     % (t, base, 'true' if mir else 'false', len(p), ',\n             '.join(lsub(s) for s in p)))
    rel = os.path.relpath(SRC, WHEELDIS)
    txt = HEADER.format(src=rel, md5=md5[:8]) + ',\n'.join(lines) + FOOTER
    open(OUT, 'w').write(txt)
    print('source %s md5 %s; base names %d; parts %d; by n %s; mirror-equal (no mirror) %s'
          % (rel, md5[:8], len(names), len(parts), dict(sorted(byn.items())), nomir))
    print('wrote %s (%d lines)' % (OUT, txt.count('\n')))

if __name__ == '__main__':
    main()
