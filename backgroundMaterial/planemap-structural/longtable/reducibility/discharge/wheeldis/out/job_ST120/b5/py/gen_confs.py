#!/usr/bin/env python3
"""ST-120 B5: the K633 configurations as Lean data (RSSTConfs.lean), from loop/k44/rsst.txt (kc lines).
Line format: name r m ringnbrs interiornbrs, with ';'-separated per interior vertex, ','-separated 0-based lists ('-' = none).
deg = |ring nbrs| + |interior nbrs|. Cross-checked against RSST-1SHOT's parser of unavoidable.conf (rcore.CONFIGS: deg, E)
and its verdicts. usage: python3 -I gen_confs.py"""
import os, sys, hashlib
H = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(H, '..', '..', '..'))            # .../wheeldis/out
WD = os.path.normpath(os.path.join(OUT, '..'))
RSST = os.path.join(WD, 'loop', 'k44', 'rsst.txt')
sys.path.insert(0, os.path.join(OUT, 'job_RSST1SHOT', 'code'))

def parse():
    res = []
    for line in open(RSST):
        f = line.split()
        if not f: continue
        name, r, m, rp, ip = f[0], int(f[1]), int(f[2]), f[3], f[4]
        rl = [[] if x == '-' else [int(y) for y in x.split(',')] for x in rp.split(';')]
        il = [[] if x == '-' else [int(y) for y in x.split(',')] for x in ip.split(';')]
        assert len(rl) == m and len(il) == m, name
        deg = [len(rl[j]) + len(il[j]) for j in range(m)]
        for j in range(m):
            for k in il[j]: assert j in il[k], (name, j, k)
        res.append((name, r, deg, il))
    return res

def main():
    C = parse(); assert len(C) == 633
    import rcore as R
    bad = 0
    for (name, r, deg, il), p in zip(C, R.CONFIGS):
        rn = name.split('_', 1)[1].replace('o', '.')
        if rn != p['name']: bad += 1; print('name', name, p['name']); continue
        U = sorted(p['deg']); assert U == list(range(r + 1, r + 1 + len(deg)))
        if [p['deg'][u] for u in U] != deg: bad += 1; print('deg', name)
        if [sorted(U.index(x) for x in p['E'][u]) for u in U] != [sorted(x) for x in il]: bad += 1; print('adj', name)
    print('cross-check vs rcore (unavoidable.conf 26aeba66):', 633 - bad, 'agree,', bad, 'differ')
    md5 = hashlib.md5(open(RSST, 'rb').read()).hexdigest()
    L = ['/-', '  GENERATED by py/gen_confs.py from loop/k44/rsst.txt (md5 %s); do not edit by hand.' % md5[:8],
         '  633 RSST configurations (unavoidable.conf order), interior only: degrees and interior adjacency (0-based).',
         '  Verdicts from loop/k44/rsst_verdicts.txt (via RSST-1SHOT rcore): D2 / C2cons (proved, 582) or none (51).',
         '-/', 'import RSSTKill', '', 'namespace SimpleGraph.SphericalMap.RSSTSeed', '',
         '/-- The 633 configurations, in `rsst.txt` order. -/', 'def k633 : List Conf := [']
    ents = []
    for (name, r, deg, il) in C:
        ents.append('  ⟨"%s", [%s], [%s]⟩' % (name, ','.join(map(str, deg)), ','.join('[%s]' % ','.join(map(str, sorted(x))) for x in il)))
    L.append(',\n'.join(ents)); L.append(']'); L.append('')
    L.append('/-- Verdict per configuration (same order): `true` = proved (D2 or C2cons), `false` = none. -/')
    L.append('def k633proved : List Bool := [%s]' % ', '.join('true' if p['proved'] else 'false' for p in R.CONFIGS))
    L.append('')
    L.append('/-- The 582 proved configurations. -/')
    L.append('def k582 : List Conf := (k633.zip k633proved).filterMap fun (K, b) => if b then some K else none')
    L.append('')
    L.append('set_option maxRecDepth 20000 in\ntheorem k633_length : k633.length = 633 := by rfl')
    L.append('')
    L.append('end SimpleGraph.SphericalMap.RSSTSeed')
    open(os.path.join(H, '..', 'RSSTConfs.lean'), 'w').write('\n'.join(L) + '\n')
    print('wrote RSSTConfs.lean;', sum(len(c[2]) for c in C), 'interior vertices; max interior', max(len(c[2]) for c in C),
          '; proved', sum(p['proved'] for p in R.CONFIGS))

main()
