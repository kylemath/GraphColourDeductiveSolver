"""job HD0 (Studio, 4 Nov): D-side Lean template on the gen_ccover3 Conf path. Input EXTRAFILE lines "name<TAB>r m ringadj intadj"
(a kc line without the name). Writes MOD.lean with `<pfx>Confs : List DCheck18.Conf` (same Conf literal as gen_ccover3's cf field),
its length, and one module per batch with `hD_i : DCheck18.dReducible (<pfx>Confs.get i) = true := by native_decide` (the hD
field of ClaimGlue.DEntry), plus an assembly `hD_all (k : Fin n)`.  usage: gen_hd.py EXTRAFILE OUTDIR MOD PFX BATCH"""
import sys, os
ef, out, mod, pfx, B = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], int(sys.argv[5])
arr = lambda L: "#[" + ", ".join("#[" + ", ".join(map(str, g)) + "]" for g in L) + "]"
items = []
for line in open(ef):
    if not line.strip(): continue
    n, kcf = line.rstrip('\n').split('\t')[:2]
    r, m, ra, ia = kcf.split(); r = int(r); m = int(m)
    ra = [[] if g == '-' else list(map(int, g.split(','))) for g in ra.split(';')]
    ia = [[] if g == '-' else list(map(int, g.split(','))) for g in ia.split(';')]
    assert len(ra) == m and len(ia) == m, n
    items.append('  { name := "%s", r := %d, m := %d,\n    ringAdj := %s,\n    intAdj := %s }' % (n, r, m, arr(ra), arr(ia)))
N = len(items)
open(os.path.join(out, mod + '.lean'), 'w').write("""import DCheck18

/-! # %s (Studio, job HD0): D-reducibility data, generated by out/job_HD0/gen_hd.py from %s (kc lines). -/

namespace %s
open DCheck18

def %sConfs : List DCheck18.Conf := [
%s]

theorem %sConfs_length : %sConfs.length = %d := by
  native_decide

end %s
""" % (mod, os.path.basename(ef), mod, pfx, ",\n".join(items), pfx, pfx, N, mod))
mods = []
for b in range(0, N, B):
    k = b // B; mm = '%sV%02d' % (mod, k); mods.append(mm)
    t = ['import ' + mod, 'open %s DCheck18' % mod, 'namespace %sV' % mod]
    for i in range(b, min(N, b + B)):
        t.append('theorem hD_%d : DCheck18.dReducible (%sConfs.get ⟨%d, by rw [%sConfs_length]; decide⟩) = true := by native_decide' % (i, pfx, i, pfx))
    t += ['end %sV' % mod] + ['#print axioms %sV.hD_%d' % (mod, i) for i in range(b, min(N, b + B))]
    open(os.path.join(out, mm + '.lean'), 'w').write('\n'.join(t) + '\n')
a = ['import ' + m for m in mods] + ['open %s DCheck18' % mod, 'namespace %sV' % mod,
     'theorem hD_all (k : Fin %d) : DCheck18.dReducible (%sConfs.get (k.cast %sConfs_length.symm)) = true := by' % (N, pfx, pfx), '  fin_cases k'] + \
    ['  · exact hD_%d' % i for i in range(N)] + ['end %sV' % mod, '#print axioms %sV.hD_all' % mod]
open(os.path.join(out, mod + 'All.lean'), 'w').write('\n'.join(a) + '\n')
print('%d entries, %d modules' % (N, len(mods)))
