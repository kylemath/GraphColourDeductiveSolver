#!/usr/bin/env python3
"""Generate DiamondKernel.lean: the same extendability facts as DiamondExt.lean, but over Fin 4
and proved by `decide +kernel` (pure kernel evaluation, no SAT solver, no native code).
Arg 1: output file; arg 2 (optional) 'full' adds the all-ring-colourings theorem (4^10 cases)."""
import sys
import dred
d = dred.DIAMOND
r, m, RA, IA = d["r"], d["m"], d["ringadj"], d["intadj"]
allk, good, levels = dred.closure(r, RA, IA, m, verbose=False)
ext = sorted(levels[0])
R = [f"r{i}" for i in range(r)]; I = [f"i{a}" for a in range(m)]
br = " ".join(R)
def int_proper(rc, ic):
    cl = [f"{ic[a]} ≠ {rc[t]}" for a in range(m) for t in RA[a]]
    cl += [f"{ic[a]} ≠ {ic[b]}" for a in range(m) for b in IA[a] if b > a]
    return " ∧ ".join(cl)
def matches(p):
    return "(" + " ∧ ".join((f"{R[i]} = {R[j]}" if p[i] == p[j] else f"{R[i]} ≠ {R[j]}")
                            for i in range(r) for j in range(i+1, r)) + ")"
o = ["""/-!
# Birkhoff diamond extendability by kernel `decide` (generated by gen_kernel.py)
Same layout as DiamondExt.lean, colours `Fin 4`, no imports, proofs by `decide +kernel`.
-/
namespace BirkhoffDiamondK
"""]
o.append("set_option synthInstance.maxSize 1000000\nset_option synthInstance.maxHeartbeats 0\n")
o.append(f"abbrev IntProper ({br} i0 i1 i2 i3 : Fin 4) : Prop :=\n  {int_proper(R, I)}\n")
o.append(f"abbrev RingProper ({br} : Fin 4) : Prop :=\n  " + " ∧ ".join(f"{R[i]} ≠ {R[(i+1)%r]}" for i in range(r)) + "\n")
o.append(f"abbrev ExtSet ({br} : Fin 4) : Prop :=\n  " + " ∨\n  ".join(matches(p) for p in ext) + "\n")
for n, k in enumerate(allk):
    lit = " ".join(map(str, k)); nm = "".join(map(str, k))
    if k in levels[0]:
        o.append(f"theorem cls_{nm} : ∃ i0 i1 i2 i3 : Fin 4, IntProper {lit} i0 i1 i2 i3 := by decide +kernel")
    else:
        o.append(f"theorem cls_{nm} : ¬ ∃ i0 i1 i2 i3 : Fin 4, IntProper {lit} i0 i1 i2 i3 := by decide +kernel")
if len(sys.argv) > 2 and sys.argv[2] == "full":
    o.append(f"""
theorem diamond_ext_iff : ∀ {br} : Fin 4, RingProper {br} →
    ((∃ i0 i1 i2 i3 : Fin 4, IntProper {br} i0 i1 i2 i3) ↔ ExtSet {br}) := by decide +kernel
""")
o.append("\nend BirkhoffDiamondK\n")
for nm in ["cls_" + "".join(map(str, allk[0]))] + (["diamond_ext_iff"] if len(sys.argv) > 2 else []):
    o.append(f"#print axioms BirkhoffDiamondK.{nm}")
open(sys.argv[1], "w").write("\n".join(o) + "\n")
