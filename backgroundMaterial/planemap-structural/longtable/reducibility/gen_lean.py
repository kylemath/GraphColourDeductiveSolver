#!/usr/bin/env python3
"""Generate DiamondExt.lean: the exact set of ring colourings of the Birkhoff diamond that extend
to its interior, as bv_decide (SAT + kernel-checked LRAT) theorems over BitVec 2 colours.

Colours are BitVec 2 (= Z2 x Z2).  For a pattern p (canonical ring colouring class), the actual
colour of canonical colour j is r at the first position where p has j; if p uses 3 colours the
fourth is r_a ^ r_b ^ r_c (XOR of the three used colours).
"""
import itertools, sys
import dred

d = dred.DIAMOND
r, m, RA, IA = d["r"], d["m"], d["ringadj"], d["intadj"]
allk, good, levels = dred.closure(r, RA, IA, m, verbose=False)
ext = sorted(levels[0])

R = [f"r{i}" for i in range(r)]
I = [f"i{a}" for a in range(m)]
binders_r = " ".join(R)


def ring_proper():
    return " ∧ ".join(f"{R[i]} ≠ {R[(i+1)%r]}" for i in range(r))


def int_proper(cols):
    cl = []
    for a in range(m):
        for t in RA[a]:
            cl.append(f"{cols[a]} ≠ {R[t]}")
        for b in IA[a]:
            if b > a:
                cl.append(f"{cols[a]} ≠ {cols[b]}")
    return " ∧ ".join(cl)


def matches(p):
    cl = []
    for i in range(r):
        for j in range(i + 1, r):
            cl.append(f"{R[i]} = {R[j]}" if p[i] == p[j] else f"{R[i]} ≠ {R[j]}")
    return "(" + " ∧ ".join(cl) + ")"


def colour_term(p, j):
    if j in p:
        return R[p.index(j)]
    # fourth colour: XOR of the three used
    firsts = [R[p.index(x)] for x in range(3)]
    return "(" + " ^^^ ".join(firsts) + ")"


out = []
out.append("""import Std.Tactic.BVDecide

/-!
# Birkhoff diamond: exact set of extendable ring colourings (generated by gen_lean.py)

Ring positions 0..5, interior vertices 0..3, same layout as StudioMathLean `DiamondCert.lean`
(`ringList = [[0,1],[1,2,3],[3,4],[0,4,5]]`, `intList = [[1,2,3],[0,2],[0,1,3],[0,2]]`).
Colours are `BitVec 2`.  `extSet r` says the ring colouring is (up to renaming) one of the 16
classes that `dred.py` finds extendable; there are 31 classes of proper ring colourings.

* `diamond_noext`  : (bv_decide) a proper ring colouring with a proper interior extension is in
  `extSet`; i.e. the other 15 classes do NOT extend.  SAT/UNSAT part, LRAT checked by the kernel.
* `diamond_ext_k`  : (bv_decide) for each extendable class an explicit extension (interior colours
  as XOR-terms of the ring colours) is proper.
* `diamond_ext_iff`: combined: for a proper ring colouring, extends ↔ extSet.
-/

namespace BirkhoffDiamond
""")
out.append(f"/-- interior colouring `i` properly extends ring colouring `r`. -/")
out.append(f"def IntProper ({binders_r} i0 i1 i2 i3 : BitVec 2) : Prop :=\n  {int_proper(I)}\n")
out.append(f"def RingProper ({binders_r} : BitVec 2) : Prop :=\n  {ring_proper()}\n")
out.append(f"/-- the ring colouring is in one of the {len(ext)} extendable classes. -/")
out.append(f"def ExtSet ({binders_r} : BitVec 2) : Prop :=\n  " + " ∨\n  ".join(matches(p) for p in ext) + "\n")

out.append(f"""/-- The 15 non-extendable classes really do not extend (UNSAT, via LRAT). -/
theorem diamond_noext ({binders_r} i0 i1 i2 i3 : BitVec 2)
    (hr : RingProper {binders_r}) (hi : IntProper {binders_r} i0 i1 i2 i3) :
    ExtSet {binders_r} := by
  simp only [RingProper, IntProper, ExtSet] at *
  bv_decide
""")
for n, p in enumerate(ext):
    w = levels and dred.extends(p, RA, IA, m)
    cols = [colour_term(p, j) for j in w]
    out.append(f"""/-- class {''.join(map(str,p))} extends: interior colours {w} up to renaming. -/
theorem diamond_ext_{n} ({binders_r} : BitVec 2) (hm : {matches(p)}) :
    IntProper {binders_r} {' '.join(cols)} := by
  simp only [IntProper] at *
  bv_decide
""")
# assemble
cases = []
for n, p in enumerate(ext):
    cols = [colour_term(p, j) for j in dred.extends(p, RA, IA, m)]
    cases.append(f"exact ⟨{', '.join(cols)}, diamond_ext_{n} {binders_r} h⟩")
alts = "\n    · ".join(cases)
pat = " | ".join(["h"] * len(ext))
out.append(f"""/-- For a proper colouring of the 6-ring: it extends to the diamond interior iff it lies in the
{len(ext)} classes of `ExtSet` (31 classes in all). -/
theorem diamond_ext_iff ({binders_r} : BitVec 2) (hr : RingProper {binders_r}) :
    (∃ i0 i1 i2 i3 : BitVec 2, IntProper {binders_r} i0 i1 i2 i3) ↔ ExtSet {binders_r} := by
  constructor
  · rintro ⟨i0, i1, i2, i3, hi⟩
    exact diamond_noext {binders_r} i0 i1 i2 i3 hr hi
  · intro hs
    simp only [ExtSet] at hs
    rcases hs with {pat}
    · {alts}

end BirkhoffDiamond

#print axioms BirkhoffDiamond.diamond_noext
#print axioms BirkhoffDiamond.diamond_ext_0
#print axioms BirkhoffDiamond.diamond_ext_iff
""")
open(sys.argv[1] if len(sys.argv) > 1 else "DiamondExt.lean", "w").write("\n".join(out))
