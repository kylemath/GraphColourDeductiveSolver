#!/usr/bin/env python3
"""Aggregate out/*.jsonl from leverage.py into leverage curves (tables to stdout as markdown, plots to plots/)."""
import json, glob, os, collections, sys, gzip
import matplotlib; matplotlib.use('Agg')
import matplotlib.pyplot as plt
os.chdir(os.path.dirname(os.path.abspath(__file__)))

def load(f):
    out = []
    for l in (gzip.open(f, 'rt') if f.endswith('.gz') else open(f)):
        try: r = json.loads(l)
        except ValueError: continue
        if 'skip' not in r and r['S'] > 0: out.append(r)
    return out

GROUPS = {}
for f in sorted(glob.glob('out/*.jsonl') + glob.glob('out/*.jsonl.gz')):
    GROUPS[os.path.basename(f).split('.')[0]] = load(f)

def agg(rows, src, dmaxbin=6):
    H = collections.defaultdict(collections.Counter); st = collections.Counter(); sh = collections.Counter()
    for r in rows:
        for k, v in r['H'].items():
            s, d = k.split('|')
            if s == src: H[min(int(d), dmaxbin)].update(v)
        st.update(r['states'])
        for d, c in r['shell'].items(): sh[min(int(d), dmaxbin)] += c
    return H, st, sh

ALLK = ('dF-1', 'dF+1', 'fill', 'unlockDL', 'lockdown', 'lockbits', 'pi_jump', 'pi_same', 'side', 'side_open', 'side_close', 'side_open_from0')
def curve(rows, src, keys=ALLK):
    H, st, sh = agg(rows, src)
    ns = st.get(src, 0); tot = {k: sum(H[d].get(k, 0) for d in H) for k in keys}
    res = []
    for d in sorted(H):
        h = H[d]; n = h['n']
        row = {'d': d, 'n': n, 'per_state': n / ns if ns else 0, 'meanK': h['size'] / n, 'rim': h['rim'] / n,
               'shell_per_hole': sh[d] / len(rows)}
        for k in keys:
            row[k] = h.get(k, 0) / n; row[k + '_share'] = h.get(k, 0) / tot[k] if tot[k] else 0
            row[k + '_per_state'] = h.get(k, 0) / ns if ns else 0
        res.append(row)
    return res, ns

def fmt_curve(name, rows, src, keys):
    c, ns = curve(rows, src)
    s = ['', '**%s, source %s** (%d holes, %d source states)' % (name, src, len(rows), ns), '',
         '| d | shell size | swaps/state | mean K | ' + ' | '.join('%s rate (share)' % k for k in keys) + ' |',
         '|---|---|---|---|' + '---|' * len(keys)]
    for r in c:
        s.append('| %s | %.1f | %.2f | %.1f | ' % (('%d' % r['d']) if r['d'] < 6 else '>=6', r['shell_per_hole'], r['per_state'], r['meanK']) +
                 ' | '.join('%.3f (%.2f)' % (r[k], r[k + '_share']) for k in keys) + ' |')
    return '\n'.join(s)

def bestnear(rows, src):
    st = collections.Counter()
    for r in rows: st.update(r['states'])
    tot = sum(v for k, v in st.items() if k.startswith(src + '_bestnear'))
    near = {int(k.split('bestnear')[1]): v for k, v in st.items() if k.startswith(src + '_bestnear')}
    far = {int(k.split('bestfar')[1]): v for k, v in st.items() if k.startswith(src + '_bestfar')}
    return tot, near, far, st.get(src + '_allbestfar', 0)

def split_word(rows):
    return [r for r in rows if r['word'] == '66666'], [r for r in rows if r['word'] != '66666' and '5' in r['word']]

if __name__ == '__main__':
    os.makedirs('plots', exist_ok=True)
    sph = GROUPS.get('sphere_frame22_28', []) + GROUPS.get('sphere_frame30_33', [])
    sets = {'sphere frame 22-28': GROUPS.get('sphere_frame22_28', []),
            'sphere frame 30-33 (sample)': GROUPS.get('sphere_frame30_33', []),
            'sphere plantri24 (sample)': GROUPS.get('sphere_plantri24', []),
            'torus': GROUPS.get('torus', []), 'rp2': GROUPS.get('rp2', []), 'klein': GROUPS.get('klein', []),
            'genus2': GROUPS.get('genus2', []), 'rp2x3': GROUPS.get('rp2x3', []),
            'game maps': GROUPS.get('gamemaps', [])}
    a, b = split_word(sph)
    sets['sphere frame 22-33, 66666 holes'] = a; sets['sphere frame 22-33, holes with a deg-5 nbr'] = b
    print('# Leverage tables (generated by analyse.py)\n')
    print('| set | holes | unfilled states | DL states | dF=2 | dF>=3 | targetless | holes with pi-cycle |')
    print('|---|---|---|---|---|---|---|---|')
    for nm, rows in sets.items():
        st = collections.Counter()
        for r in rows: st.update(r['states'])
        print('| %s | %d | %d | %d | %d | %d | %d | %d |' % (nm, len(rows), st['U'], st['DL'], st['D2'], st['deep'],
              st['targetless'], sum(1 for r in rows if r['npicyc'] > 0)))
    K1 = ('dF-1', 'dF+1', 'lockdown', 'lockbits')
    K2 = ('dF-1', 'unlockDL', 'pi_jump', 'pi_same')
    for nm, rows in sets.items():
        if not rows: continue
        print('\n## %s' % nm)
        print(fmt_curve(nm, rows, 'U', K1))
        print(fmt_curve(nm, rows, 'DL', K2))
        for src in ('D2', 'deep'):
            if sum(r['states'].get(src, 0) for r in rows): print(fmt_curve(nm, rows, src, ('dF-1', 'dF+1', 'unlockDL')))
        if nm == 'game maps':
            for r in rows: print('- %s hole %d word %s: S=%d unfilled=%d maxdF=%d' % (r['name'], r['hole'], r['word'], r['S'], r['unfilled'], r['maxdF']))
        print(fmt_curve(nm, rows, 'D2', ('side', 'side_open', 'side_close', 'side_open_from0')))
        for src in ('U', 'DL', 'D2', 'deep'):
            tot, near, far, allfar = bestnear(rows, src)
            if tot: print('\n%s: states with a dF-reducing move %d; nearest such move at d: %s; farthest at d: %s; only far (d>=2) best moves: %d (%.3f)'
                          % (src, tot, dict(sorted(near.items())), dict(sorted(far.items())), allfar, allfar / tot))
    # stratified: D2 (dF = 2) unlock-and-descend rate per swap, by surface and order bin
    print('\n## Stratified: P(dF-1) per swap from dF = 2 states, by d; surface x order\n')
    print('| surface | n | holes | D2 states | d=1 | d=2 | d=3 | d=4 | d>=5 | swaps/state d=1,2,3,4,>=5 |')
    print('|---|---|---|---|---|---|---|---|---|---|')
    allrows = [r for g in ('sphere_frame22_28', 'sphere_frame30_33', 'sphere_plantri24', 'torus', 'rp2', 'klein', 'genus2', 'rp2x3') for r in GROUPS.get(g, [])]
    bins = [(16, 20), (21, 24), (25, 28), (29, 33), (34, 60)]
    for r in GROUPS.get('sphere_plantri24', []): r['surface'] = 'sphere-random24'
    for r in GROUPS.get('sphere_frame22_28', []) + GROUPS.get('sphere_frame30_33', []): r['surface'] = 'sphere-frame'
    for surf in ('sphere-frame', 'sphere-random24', 'torus', 'rp2', 'klein', 'genus2', 'rp2x3'):
        for lo, hi in bins:
            rows = [r for r in allrows if r['surface'] == surf and lo <= r['n'] <= hi]
            if not rows: continue
            H, st, _ = agg(rows, 'D2', dmaxbin=5)
            if not st['D2']: continue
            cells = ['%.3f' % (H[d].get('dF-1', 0) / H[d]['n']) if H[d]['n'] >= 50 else '-' for d in range(1, 6)]
            ps = ','.join('%.2f' % (H[d]['n'] / st['D2']) for d in range(1, 6))
            print('| %s | %d-%d | %d | %d | %s | %s |' % (surf, lo, hi, len(rows), st['D2'], ' | '.join(cells), ps))
    # by hole eccentricity e (largest d present): normalises for the finite radius of the map
    print('\n## By hole eccentricity e: P(dF-1) per swap from dF = 2 states at d = 1..e (rate / rate at d=1 in brackets)\n')
    print('| surface | e | holes | D2 states | d=1 | d=2 | d=3 | d=4 | d=5 | d=6 |')
    print('|---|---|---|---|---|---|---|---|---|---|')
    for surf in ('sphere-frame', 'sphere-random24', 'torus', 'rp2', 'klein', 'genus2', 'rp2x3'):
        for e in range(3, 8):
            rows = [r for r in allrows if r['surface'] == surf and max(int(k) for k in r['shell']) == e]
            if not rows: continue
            H, st, _ = agg(rows, 'D2', dmaxbin=9)
            if st['D2'] < 200: continue
            r1 = H[1].get('dF-1', 0) / H[1]['n']
            cells = ['%.3f (%.2f)' % (H[d].get('dF-1', 0) / H[d]['n'], H[d].get('dF-1', 0) / H[d]['n'] / r1) if H[d]['n'] >= 50 else '-' for d in range(1, 7)]
            print('| %s | %d | %d | %d | %s |' % (surf, e, len(rows), st['D2'], ' | '.join(cells)))
    # plots
    plotsets = [('sphere frame 22-28', 'C0', '-'), ('sphere frame 30-33 (sample)', 'C1', '-'), ('sphere plantri24 (sample)', 'C2', '-'),
                ('torus', 'C3', '--'), ('rp2', 'C4', '--'), ('klein', 'C5', '--'), ('genus2', 'C6', '--'), ('game maps', 'k', ':')]
    for src, key, ttl in [('U', 'dF-1', 'P(swap at distance d reduces dF), unfilled states'),
                          ('D2', 'dF-1', 'P(swap at d reduces dF), states with dF = 2'),
                          ('DL', 'unlockDL', 'P(swap at d unlocks a DL state)'),
                          ('DL', 'pi_jump', 'P(swap at d moves DL -> DL on another pi-orbit)'),
                          ('D2', 'side_open', 'P(sideways swap at d adds a rim-touching dF-reducing move), dF = 2 states'),
                          ('U', 'lockbits', 'P(swap at d changes a lock bit), unfilled -> unfilled')]:
        fig, ax = plt.subplots(1, 3, figsize=(14, 4))
        for nm, col, ls in plotsets:
            rows = sets.get(nm) or []
            if not rows: continue
            c, ns = curve(rows, src)
            if not c: continue
            c = [r for r in c if r['n'] >= 500]     # drop thin tail bins
            ds = [r['d'] for r in c]
            ax[0].plot(ds, [r[key] for r in c], ls, color=col, marker='o', label=nm)
            ax[1].plot(ds, [r['per_state'] for r in c], ls, color=col, marker='o', label=nm)
            ax[2].plot(ds, [r[key + '_per_state'] for r in c], ls, color=col, marker='o', label=nm)
        ax[0].set_title('rate per swap'); ax[1].set_title('swaps available per state'); ax[2].set_title('successful swaps per state')
        for x in ax: x.set_xlabel('d(K) = distance hole -> nearest vertex of K (6 = >=6)'); x.grid(alpha=.3)
        ax[0].legend(fontsize=7); fig.suptitle(ttl); fig.tight_layout()
        fig.savefig('plots/%s_%s.png' % (src, key.replace('-', 'm').replace('+', 'p')), dpi=90); plt.close(fig)
